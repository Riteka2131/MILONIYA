-- ---------- ПРОФИЛИ ----------
create table if not exists public.profiles (
    id uuid primary key references auth.users(id) on delete cascade,
    username text not null,
    created_at timestamptz not null default now(),
    constraint profiles_username_len check (char_length(username) between 3 and 20),
    constraint profiles_username_format check (username ~ '^[A-Za-zА-Яа-яЁё0-9_]+$')
);

create unique index if not exists profiles_username_lower_key
    on public.profiles (lower(username));

alter table public.profiles enable row level security;

drop policy if exists "profiles_select_all" on public.profiles;
create policy "profiles_select_all" on public.profiles
    for select using (true);

drop policy if exists "profiles_insert_own" on public.profiles;
create policy "profiles_insert_own" on public.profiles
    for insert with check (auth.uid() = id);

drop policy if exists "profiles_update_own" on public.profiles;
create policy "profiles_update_own" on public.profiles
    for update using (auth.uid() = id) with check (auth.uid() = id);

-- ---------- РЕЗУЛЬТАТЫ ИГР ----------
create table if not exists public.scores (
    id bigint generated by default as identity primary key,
    user_id uuid not null references public.profiles(id) on delete cascade,
    game text not null check (game in ('snake', 'ttt', '2048')),
    score integer not null check (score >= 0 and score <= 100000000),
    created_at timestamptz not null default now()
);

create index if not exists scores_game_score_idx
    on public.scores (game, score desc);

create index if not exists scores_user_game_idx
    on public.scores (user_id, game);

alter table public.scores enable row level security;

drop policy if exists "scores_select_all" on public.scores;
create policy "scores_select_all" on public.scores
    for select using (true);

drop policy if exists "scores_insert_own" on public.scores;
create policy "scores_insert_own" on public.scores
    for insert with check (auth.uid() = user_id);

-- ---------- ПРОФИЛЬ ПРИ РЕГИСТРАЦИИ ----------
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
    uname text;
begin
    uname := coalesce(
        nullif(trim(new.raw_user_meta_data->>'username'), ''),
        split_part(new.email, '@', 1)
    );
    uname := regexp_replace(uname, '[^A-Za-zА-Яа-яЁё0-9_]', '', 'g');

    if char_length(uname) < 3 then
        uname := 'player_' || substr(replace(new.id::text, '-', ''), 1, 6);
    end if;
    uname := left(uname, 20);

    begin
        insert into public.profiles (id, username) values (new.id, uname);
    exception when unique_violation then
        insert into public.profiles (id, username)
        values (new.id, left(uname, 15) || '_' || substr(replace(new.id::text, '-', ''), 1, 4));
    end;

    return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
    after insert on auth.users
    for each row execute function public.handle_new_user();

-- ---------- ЛИДЕРБОРД ----------
-- Для змейки и 2048 — лучший счёт, для крестиков-ноликов — количество побед.
drop view if exists public.leaderboard;
create view public.leaderboard
with (security_invoker = true)
as
select
    s.game,
    s.user_id,
    p.username,
    case when s.game = 'ttt' then count(*)::int else max(s.score)::int end as best,
    max(s.created_at) as last_played
from public.scores s
join public.profiles p on p.id = s.user_id
group by s.game, s.user_id, p.username;

grant usage on schema public to anon, authenticated;
grant select on public.profiles to anon, authenticated;
grant insert, update on public.profiles to authenticated;
grant select on public.scores to anon, authenticated;
grant insert on public.scores to authenticated;
grant select on public.leaderboard to anon, authenticated;
